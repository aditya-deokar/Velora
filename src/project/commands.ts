function skillsFaultCode(error: unknown): string {
  const code = error instanceof Error && "code" in error && typeof error.code === "string" ? error.code : "project-error";
  if (code === "conflict") return "ERR_SKILL_CONFLICT";
  if (code === "denied-path") return "denied-path";
  if (code === "invalid-scope" || code === "invalid-input" || code === "invalid-file") return code;
  return code;
}
async function readSkillVersion(absoluteFile: string): Promise<string | undefined> {
  const text = await services.readAbsoluteText(absoluteFile);
  if (text === undefined) return undefined;
  const parsed = parseSkillFrontmatter(text);
  if ("issues" in parsed) return undefined;
  const version = parsed.frontmatter["version"];
  return typeof version === "string" ? version : undefined;
}
export async function executeSkillsCommand(
  operation: "install-skills" | "list-skills" | "check-skills",
  input: unknown,
  context: { root: string; version?: string },
): Promise<SkillsResult> {
  try {
    if (!context || typeof context.root !== "string")
      return skillsFailure([{ code: "invalid-scope", message: "Provide an absolute local project directory.", path: "skills" }]);
    const root = await services.canonicalRoot(context.root);
    const cliVersion = typeof context.version === "string" && context.version ? context.version : undefined;
    if (operation === "install-skills") {
      const parsed = z.strictObject({
        dir: z.string().min(1),
        agent: z.enum(AGENT_NAMES).optional(),
        source: z.string().min(1).optional(),
      }).safeParse(input);
      if (!parsed.success)
        return skillsFailure(parsed.error.issues.map((issue) => ({ code: "invalid-input", message: issue.message, path: `skills.${issue.path.join(".") || "dir"}` })));
      let targetDir: string;
      let sourceDir: string | undefined;
      try {
        targetDir = (await services.resolveSkillsDir(root, parsed.data.dir))!;
        sourceDir = await services.resolveSkillsSource(root, parsed.data.source);
      } catch (error) {
        const known = error instanceof Error && "code" in error;
        return skillsFailure([{ code: skillsFaultCode(error), message: error instanceof Error ? error.message : "Unable to resolve skills paths.", path: "skills.dir" }]);
      }
      if (!sourceDir)
        return skillsFailure([{ code: "ERR_SKILL_MISSING", message: "Packaged Velora skills were not found. Run from a Velora checkout or pass --source.", path: "skills.source" }]);
      let rels: string[];
      try {
        rels = (await services.listAbsoluteTree(sourceDir)).filter((rel) => services.isVeloraSkillFile(rel));
      } catch (error) {
        const known = error instanceof Error && "code" in error;
        return skillsFailure([{ code: skillsFaultCode(error), message: "Unable to list packaged skills.", path: "skills.source" }]);
      }
      if (!rels.length)
        return skillsFailure([{ code: "ERR_SKILL_MISSING", message: "Packaged Velora skills tree is empty.", path: "skills.source" }]);
      try {
        await services.ensureAbsoluteDir(targetDir);
      } catch (error) {
        return skillsFailure([{ code: skillsFaultCode(error), message: error instanceof Error ? error.message : "Unable to prepare the skills directory.", path: "skills.dir" }]);
      }
      const installed: string[] = [];
      const versions: Record<string, string> = {};
      let changed = false;
      // Join with forward slashes: skills trees use posix separators.
      const joinAbs = (base: string, rel: string) => `${base}/${rel}`;
      for (const rel of rels) {
        const from = `${sourceDir}/${rel}`;
        const to = joinAbs(targetDir, rel);
        const sourceText = await services.readAbsoluteText(from);
        if (sourceText === undefined)
          return skillsFailure([{ code: "ERR_SKILL_MISSING", message: `Packaged skill file ${rel} disappeared during install.`, path: `skills.${rel}` }]);
        const existing = await services.readAbsoluteText(to);
        if (existing !== undefined && existing !== sourceText)
          return skillsFailure([{ code: "ERR_SKILL_CONFLICT", message: `Skill file ${rel} differs in ${targetDir}. Preserve or move it, then retry.`, path: `skills.${rel}` }]);
        if (existing === undefined) {
          try {
            await services.writeAbsoluteText(to, sourceText, undefined);
          } catch (error) {
            return skillsFailure([{ code: skillsFaultCode(error) === "conflict" ? "ERR_SKILL_CONFLICT" : skillsFaultCode(error), message: error instanceof Error ? error.message : `Unable to install ${rel}.`, path: `skills.${rel}` }]);
          }
          changed = true;
        }
        installed.push(rel);
        const skillName = services.skillNameFromRel(rel);
        if (skillName) {
          const version = await readSkillVersion(to);
          if (version) versions[skillName] = version;
        }
      }
      const agent = parsed.data.agent as AgentName | undefined;
      const snippet = agent ? agentSnippet(agent, targetDir) : undefined;
      return { success: true as const, command: "skills" as const, data: { kind: "install", dir: targetDir, installed, changed, versions, ...(snippet ? { snippet } : {}) } };
    }
    if (operation === "list-skills") {
      const parsed = z.strictObject({
        dir: z.string().min(1).optional(),
        source: z.string().min(1).optional(),
      }).safeParse(input);
      if (!parsed.success)
        return skillsFailure(parsed.error.issues.map((issue) => ({ code: "invalid-input", message: issue.message, path: `skills.${issue.path.join(".") || "input"}` })));
      let sourceDir: string | undefined;
      let targetDir: string | undefined;
      try {
        sourceDir = await services.resolveSkillsSource(root, parsed.data.source);
        targetDir = await services.resolveSkillsDir(root, parsed.data.dir);
      } catch (error) {
        return skillsFailure([{ code: skillsFaultCode(error), message: error instanceof Error ? error.message : "Unable to resolve skills paths.", path: "skills" }]);
      }
      const available: { name: string; version: string; path: string }[] = [];
      const installed: { name: string; version: string; path: string }[] = [];
      if (sourceDir) {
        const rels = (await services.listAbsoluteTree(sourceDir)).filter((rel) => services.skillNameFromRel(rel));
        for (const rel of rels.sort()) {
          const name = services.skillNameFromRel(rel)!;
          const version = (await readSkillVersion(`${sourceDir}/${rel}`)) ?? "0.0.0";
          available.push({ name, version, path: rel });
        }
      }
      if (targetDir) {
        const rels = (await services.listAbsoluteTree(targetDir)).filter((rel) => services.skillNameFromRel(rel));
        for (const rel of rels.sort()) {
          const name = services.skillNameFromRel(rel)!;
          const version = (await readSkillVersion(`${targetDir}/${rel}`)) ?? "0.0.0";
          installed.push({ name, version, path: rel });
        }
      }
      const byAvailable = new Map(available.map((skill) => [skill.name, skill.version]));
      const drift: { name: string; expected: string; found: string }[] = [];
      for (const skill of installed) {
        const expected = byAvailable.get(skill.name);
        if (expected && expected !== skill.version) drift.push({ name: skill.name, expected, found: skill.version });
        else if (cliVersion && skill.version !== cliVersion) drift.push({ name: skill.name, expected: cliVersion, found: skill.version });
      }
      return { success: true as const, command: "skills" as const, data: { kind: "list", ...(sourceDir ? { source: sourceDir } : {}), ...(targetDir ? { dir: targetDir } : {}), available, installed, drift } };
    }
    const parsed = z.strictObject({
      dir: z.string().min(1).optional(),
      source: z.string().min(1).optional(),
    }).safeParse(input);
    if (!parsed.success)
      return skillsFailure(parsed.error.issues.map((issue) => ({ code: "invalid-input", message: issue.message, path: `skills.${issue.path.join(".") || "input"}` })));
    let checkDir: string | undefined;
    try {
      const sourceDir = await services.resolveSkillsSource(root, parsed.data.source);
      checkDir = (await services.resolveSkillsDir(root, parsed.data.dir)) ?? sourceDir;
    } catch (error) {
      return skillsFailure([{ code: skillsFaultCode(error), message: error instanceof Error ? error.message : "Unable to resolve skills paths.", path: "skills" }]);
    }
    if (!checkDir)
      return skillsFailure([{ code: "ERR_SKILL_MISSING", message: "No skills tree found. Run from a Velora checkout or pass --source/--dir.", path: "skills" }]);
    const rels = await services.listAbsoluteTree(checkDir);
    const byRel = new Map(rels.map((rel) => [rel, true]));
    const skills: { name: string; version: string; ok: boolean; issues: { code: string; path: string; message: string }[] }[] = [];
    const failures: CliIssue[] = [];
    for (const name of VELORA_SKILL_NAMES) {
      const rel = name === "velora" ? "velora/SKILL.md" : `${name}/SKILL.md`;
      const absolute = `${checkDir}/${rel}`;
      const text = byRel.has(rel) ? await services.readAbsoluteText(absolute) : undefined;
      if (text === undefined) {
        const issue = normalizeIssue({ code: "ERR_SKILL_MISSING", message: `Skill "${name}" is missing (${rel}). Re-run velora skills install --dir ${checkDir}.`, path: `skills.${name}` });
        failures.push(issue);
        skills.push({ name, version: "0.0.0", ok: false, issues: [{ code: issue.code, path: issue.path ?? `skills.${name}`, message: issue.message }] });
        continue;
      }
      const { frontmatter, issues } = validateSkillContent(name, text);
      const version = typeof frontmatter.version === "string" ? frontmatter.version : "0.0.0";
      const versionIssues: { code: string; path: string; message: string }[] = [];
      if (cliVersion && version !== cliVersion)
        versionIssues.push({ code: "ERR_SKILL_VERSION", path: `skills.${name}:version`, message: `Skill "${name}" pins ${version} but the CLI is ${cliVersion}. Re-run velora skills install --dir ${checkDir}.` });
      const all = [...issues, ...versionIssues];
      if (all.length) for (const issue of all) failures.push(normalizeIssue({ code: issue.code, message: issue.message, path: issue.path }));
      skills.push({ name, version, ok: all.length === 0, issues: all });
    }
    if (failures.length) return { success: false as const, command: "skills" as const, issues: failures, next: nextForIssues(failures) };
    return { success: true as const, command: "skills" as const, data: { kind: "check", ...(parsed.data.dir ? { dir: checkDir } : { source: checkDir }), skills } };
  } catch (error) {
    const known = error instanceof Error && "code" in error && "target" in error;
    return skillsFailure([{ code: known ? skillsFaultCode(error) : "project-error",
      message: known ? error.message : "Unable to manage skills. Check local files and permissions, then retry.",
      ...(known && typeof error.target === "string" ? { path: error.target } : {}) }]);
  }
}


// SOURCE OF TRUTH: executeTemplateCommand template catalog and scaffolding operations.
// WHAT: list/show/check the shipped templates, and create-only scaffolding of templated scenes
// (new scene) and blueprint compositions (new video) from the user's real component or route.
// WHY: templates are starting points the creator owns; every check runs before any write and
// the written pair is re-validated through the same discovery the studio uses.
// WHERE: cli/index adapts `velora templates` and `velora new`; core/templates owns the catalog,
// project/templates generates file text, services performs exclusive writes.
export type TemplateCommandResult =
  | { success: true; command: "templates" | "new"; data: unknown; warnings?: CliIssue[]; next?: string[] }
  | { success: false; command: "templates" | "new"; issues: CliIssue[]; next: string[] };
const NewSceneInputSchema = z.strictObject({
  template: z.string().min(1), id: z.string().min(1), title: z.string().trim().min(1).max(200).optional(),
  component: z.string().min(1).optional(), route: z.string().optional(),
  aspect: z.string().optional(), durationMs: z.number().optional(), set: z.record(z.string(), z.string()).default({}),
});
const NewVideoInputSchema = z.strictObject({
  blueprint: z.string().min(1), id: z.string().min(1), title: z.string().trim().min(1).max(200).optional(),
  component: z.string().min(1).optional(), route: z.string().optional(), aspect: z.string().optional(),
});
type PlannedFile = { path: string; text: string };
function templateFault(code: string, message: string, path?: string): never {
  throw Object.assign(new Error(message), { code, target: path ?? "template" });
}
async function resolveSlot(root: string, input: { component?: string; route?: string }): Promise<{ slot: Slot; warnings: CliIssue[] }> {
  if (input.component !== undefined && input.route !== undefined) templateFault("ERR_INVALID_FLAG_COMBINATION", "Pass either --component or --route, not both.", "slot");
  if (input.route !== undefined) {
    // Git Bash (MSYS) rewrites arguments that start with "/" into Windows paths before Node sees them.
    if (/^[A-Za-z]:[\\/]/.test(input.route)) templateFault("ERR_ROUTE_INVALID", `Received ${input.route}, which looks like a shell-rewritten path: Git Bash on Windows converts arguments starting with "/". Re-run with MSYS_NO_PATHCONV=1 (for example MSYS_NO_PATHCONV=1 npx velora new ...) or from PowerShell or cmd.`, "route");
    const route = RouteSchema.safeParse(input.route);
    if (!route.success) templateFault("ERR_ROUTE_INVALID", route.error.issues[0].message, "route");
    return { slot: { kind: "route", route: route.data }, warnings: [] };
  }
  if (input.component !== undefined) {
    const [file, exportName, ...rest] = input.component.split("#");
    if (rest.length || !file || !/\.[cm]?[jt]sx?$/.test(file)) templateFault("ERR_COMPONENT_EXPORT_MISSING", "Use --component path/to/File.tsx#ExportName (omit #ExportName for the default export).", "component");
    const target = services.relativeTarget(file.replace(/^\.\//, ""));
    const source = await services.readText(root, target, 2_000_000);
    if (source === undefined) templateFault("ERR_COMPONENT_EXPORT_MISSING", `Component file ${target} was not found in this project.`, "component");
    const found = componentExport(source, target, exportName || undefined);
    if (!found) templateFault("ERR_COMPONENT_EXPORT_MISSING", `${target} has no ${exportName ? `export named ${exportName}` : "default export"}.`, "component");
    return { slot: { kind: "component", importPath: sceneImportPath(target), exportName: exportName || found.name, isDefault: found.isDefault }, warnings: [] };
  }
  return { slot: { kind: "placeholder" }, warnings: [normalizeIssue({ code: "WARN_TEMPLATE_PLACEHOLDER", message: "No --component or --route given: the scene uses a SlotPlaceholder until you replace it.", path: "slot" })] };
}
async function initializedProject(root: string): Promise<ProjectState> {
  const state = await stateFor(root);
  if (!state.project) throw fault("not-initialized", "Run velora init in this project before creating scenes.");
  return state.project;
}
function planScene(manifest: TemplateManifest, overrides: Record<string, string | number>, id: string, title: string | undefined, aspect: Aspect, slot: Slot, extension: "tsx" | "jsx"): { files: PlannedFile[]; durationMs: number } {
  if (!SceneRecipeIdSchema.safeParse(id).success) templateFault("invalid-input", "Use a lowercase scene slug for --id (letters, digits and single hyphens).", "id");
  if (!manifest.aspects.includes(aspect)) templateFault("ERR_TEMPLATE_ASPECT", `Template ${manifest.id} supports ${manifest.aspects.join(", ")}, not ${aspect}.`, "aspect");
  const resolved = resolveTemplateParams(manifest, overrides);
  if (resolved.issues.length) throw Object.assign(new Error(resolved.issues.map(issue => issue.message).join(" ")), { code: "ERR_TEMPLATE_PARAM", target: resolved.issues[0].path, issues: resolved.issues });
  const subject = ASPECT_FRAMES[aspect].subject;
  const definition = templateDefinition(manifest, resolved.params, aspect);
  const scaffold = scaffoldScene({ id, title: title ?? manifest.title, manifest, params: resolved.params, aspect, definition, subject, slot });
  const base = `${SCENE_RECIPE_DIRECTORY}/${id}`;
  return { files: [{ path: `${base}.scene.json`, text: scaffold.recipe }, { path: `${base}.${extension}`, text: scaffold.binding }], durationMs: definition.motion.durationMs };
}
// Branded bindings import velora.brand.json; scaffold a default one (create-only) when the project has none.
async function withBrandFile(root: string, manifests: TemplateManifest[], files: PlannedFile[]): Promise<void> {
  if (!manifests.some(manifest => manifest.composite)) return;
  if (await services.readText(root, BRAND_FILE, 256_000) !== undefined) return;
  const brand = BrandSchema.parse({ version: 1, name: await packageTitle(root) });
  files.push({ path: BRAND_FILE, text: JSON.stringify({ $schema: BRAND_SCHEMA_POINTER, ...brand }, null, 2) + "\n" });
}
/** The story brief written beside a blueprint composition: structure, shot list and the next commands. */
function blueprintBrief(blueprint: Blueprint, id: string, scenes: { id: string; recipe: string; startMs: number; durationMs: number; transition?: { type: string; durationMs: number; sfx?: unknown } }[], durationMs: number): string {
  const seconds = (ms: number) => (ms / 1000).toFixed(1);
  const rows = scenes.map((scene, index) => `| ${index + 1} | ${seconds(scene.startMs)}-${seconds(scene.startMs + scene.durationMs)} s | ${blueprint.scenes[index].section ?? ""} | ${blueprint.scenes[index].template} | ${scene.transition ? `${scene.transition.type} ${scene.transition.durationMs} ms${scene.transition.sfx ? " + sfx" : ""}` : "cut"} |`);
  return `# ${blueprint.title}

${blueprint.summary}

## Story

${blueprint.brief}

Structure: Hook, then Problem, Reveal, Proof and a call to action. Emotion and story come first; rhythm and eye-trace serve them.

## Shot list (${seconds(durationMs)} s)

| # | Time | Section | Template | Into this shot |
|---|---|---|---|---|
${rows.join("\n")}

## Next

1. Rewrite the copy (\`--set\` params in each scene's recipe \`template.params\`, or the bindings) and \`${id}.captions.srt\`${blueprint.captions.length ? "" : " (none in this blueprint)"}.
2. Add licensed music to \`assets/\`, reference it in \`${id}.composition.json\` (\`assets\` + \`audio\` with \`"kind": "music"\`), then: \`velora audio beats --composition ${id}.composition.json --write-markers --json\` and \`velora compose snap --composition ${id}.composition.json --to beats --json\` (add \`--write\` to apply).
3. \`velora review --composition ${id}.composition.json --json\`, then \`velora frames --composition ${id}.composition.json --out ${id}-board --every 30 --contact-sheet --json\`.
4. \`velora render --composition ${id}.composition.json --out ${id}.mp4 --quality draft --json\`; the master: \`--quality master\`.
`;
}
async function writePlanned(root: string, files: PlannedFile[]): Promise<void> {
  for (const file of files) {
    const siblings = file.path.endsWith(".scene.json") ? [file.path] : [file.path.replace(/\.[jt]sx$/, ".tsx"), file.path.replace(/\.[jt]sx$/, ".jsx")];
    for (const candidate of siblings)
      if (await services.readText(root, candidate) !== undefined) templateFault("ERR_SCENE_EXISTS", `${candidate} already exists. Choose another --id or move the existing scene.`, candidate);
  }
  for (const file of files) await services.atomicWrite(root, file.path, file.text, undefined);
}
async function bindingExtension(root: string, project: ProjectState): Promise<"tsx" | "jsx"> {
  return project.entry.endsWith(".jsx") || (project.adapter !== undefined && await services.readText(root, "tsconfig.json") === undefined) ? "jsx" : "tsx";
}
function templateSummary(manifest: TemplateManifest) {
  const { id, title, summary, category, tags, aspects } = manifest;
  return { id, title, summary, category, tags, aspects, params: manifest.params.map(param => param.name), example: `velora new scene --template ${id} --id my-${id} --route /` };
}
export async function executeTemplateCommand(operation: "list-templates" | "show-template" | "check-templates" | "new-scene" | "new-video", input: Record<string, unknown>, context: { root: string }): Promise<TemplateCommandResult> {
  const command = operation.startsWith("new") ? "new" as const : "templates" as const;
  try {
    if (operation === "list-templates") {
      const { category, tag, aspect } = input as { category?: string; tag?: string; aspect?: string };
      const templates = TEMPLATE_CATALOG.filter(t => (!category || t.category === category) && (!tag || (t.tags as string[]).includes(tag)) && (!aspect || (t.aspects as string[]).includes(aspect)));
      return { success: true, command, data: { templates: templates.map(templateSummary), blueprints: BLUEPRINT_CATALOG.map(({ id, title, summary, aspects, scenes }) => ({ id, title, summary, aspects, scenes: scenes.map(scene => scene.template) })) } };
    }
    if (operation === "show-template") {
      const id = String(input.id ?? "");
      const manifest = findTemplate(id), blueprint = findBlueprint(id);
      if (!manifest && !blueprint) templateFault("ERR_TEMPLATE_NOT_FOUND", `No template or blueprint "${id}". Run velora templates ls --json.`, "id");
      if (blueprint) return { success: true, command, data: { blueprint, example: `velora new video --blueprint ${blueprint.id} --id launch --route /` } };
      return { success: true, command, data: { template: manifest, examples: [
        `velora new scene --template ${manifest!.id} --id my-${manifest!.id} --route /`,
        `velora new scene --template ${manifest!.id} --id my-${manifest!.id} --component src/App.tsx#App --set intensity=standard`,
      ] } };
    }
    if (operation === "check-templates") {
      const id = input.id === undefined ? undefined : String(input.id);
      const manifests = id === undefined ? TEMPLATE_CATALOG : [findTemplate(id) ?? templateFault("ERR_TEMPLATE_NOT_FOUND", `No template "${id}". Run velora templates ls --json.`, "id")];
      const results = manifests.map(manifest => {
        const failures = manifest.aspects.flatMap(aspect => (["subtle", "standard", "dramatic"] as const).flatMap(intensity =>
          certifyTemplate(manifest, resolveTemplateParams(manifest, { intensity }).params, aspect)));
        return { id: manifest.id, certified: failures.length === 0, failures };
      });
      const failed = results.filter(result => !result.certified);
      if (failed.length) return { success: false, command, issues: failed.flatMap(result => result.failures).map(normalizeIssue), next: ["velora templates show --id " + failed[0].id] };
      return { success: true, command, data: { templates: results } };
    }
    const root = await services.canonicalRoot(context.root);
    if (operation === "new-scene") {
      const parsed = NewSceneInputSchema.safeParse(input);
      if (!parsed.success) templateFault("invalid-input", parsed.error.issues[0].message, parsed.error.issues[0].path.join("."));
      const request = parsed.data;
      const manifest = findTemplate(request.template) ?? templateFault("ERR_TEMPLATE_NOT_FOUND", `No template "${request.template}". Run velora templates ls --json.`, "template");
      const aspect = AspectSchema.safeParse(request.aspect ?? "16:9");
      if (!aspect.success) templateFault("ERR_TEMPLATE_ASPECT", "Use --aspect 16:9, 21:9, 1:1, 4:5 or 9:16.", "aspect");
      const project = await initializedProject(root);
      const { slot, warnings } = await resolveSlot(root, request);
      const overrides: Record<string, string | number> = { ...request.set, ...(request.durationMs !== undefined ? { durationMs: request.durationMs } : {}) };
      const plan = planScene(manifest, overrides, request.id, request.title, aspect.data, slot, await bindingExtension(root, project));
      await withBrandFile(root, [manifest], plan.files);
      await writePlanned(root, plan.files);
      const catalog = await discoverRecipes(root);
      const sceneIssues = catalog.issues.filter(issue => issue.path.startsWith(plan.files[0].path));
      if (sceneIssues.length) return { success: false, command, issues: sceneIssues.map(issue => normalizeIssue({ code: "ERR_SCENE_INVALID", ...issue })), next: ["velora validate --json"] };
      return { success: true, command, data: { files: plan.files.map(file => file.path), scene: request.id, template: manifest.id, aspect: aspect.data, durationMs: plan.durationMs, slot: slot.kind },
        ...(warnings.length ? { warnings } : {}),
        next: [...(project.adapter ? ["velora sync --json"] : []), `velora shot --scene ${request.id} --time ${Math.round(plan.durationMs / 2)} --out ${request.id}.png --json`, `velora open --scene ${request.id} --url <origin>`] };
    }
    const parsed = NewVideoInputSchema.safeParse(input);
    if (!parsed.success) templateFault("invalid-input", parsed.error.issues[0].message, parsed.error.issues[0].path.join("."));
    const request = parsed.data;
    const blueprint = findBlueprint(request.blueprint) ?? templateFault("ERR_TEMPLATE_NOT_FOUND", `No blueprint "${request.blueprint}". Run velora templates ls --json.`, "blueprint");
    if (!SceneRecipeIdSchema.safeParse(request.id).success) templateFault("invalid-input", "Use a lowercase slug for --id (letters, digits and single hyphens).", "id");
    const aspect = AspectSchema.safeParse(request.aspect ?? blueprint.aspects[0]);
    if (!aspect.success || !blueprint.aspects.includes(aspect.data)) templateFault("ERR_TEMPLATE_ASPECT", `Blueprint ${blueprint.id} supports ${blueprint.aspects.join(", ")}.`, "aspect");
    const project = await initializedProject(root);
    const { slot, warnings } = await resolveSlot(root, request);
    const extension = await bindingExtension(root, project);
    const files: PlannedFile[] = [];
    const scenes: { id: string; recipe: string; startMs: number; durationMs: number }[] = [];
    let cursor = 0;
    const markers: { atMs: number; label: string; kind: string }[] = [];
    blueprint.scenes.forEach((scene, index) => {
      const manifest = findTemplate(scene.template)!;
      const sceneId = `${request.id}-${index + 1}-${manifest.id}`;
      const plan = planScene(manifest, scene.params, sceneId, `${request.title ?? blueprint.title}: ${manifest.title}`, aspect.data, slot, extension);
      files.push(...plan.files);
      // Overlap transitions start the shot inside the previous one; everything else butt-joins.
      const overlap = scene.transition && index > 0 && isOverlapTransition(scene.transition.type) ? scene.transition.durationMs : 0;
      const startMs = cursor - overlap;
      scenes.push({ id: `shot-${index + 1}`, recipe: sceneId, startMs, durationMs: plan.durationMs, ...(scene.transition && index > 0 ? { transition: scene.transition } : {}) });
      if (scene.section) markers.push({ atMs: startMs + overlap, label: scene.section, kind: "section" });
      cursor = startMs + plan.durationMs;
    });
    // V2 graphics: scaffolded as their own scenes (backdrop off where the template has one).
    const overlays = blueprint.overlays.map((overlay, index) => {
      const manifest = findTemplate(overlay.template)!;
      const sceneId = `${request.id}-ov${index + 1}-${manifest.id}`;
      const params = { ...overlay.params, ...(manifest.params.some(param => param.name === "backdrop") ? { backdrop: "off" } : {}) };
      files.push(...planScene(manifest, params, sceneId, `${request.title ?? blueprint.title}: ${manifest.title} (overlay)`, aspect.data, { kind: "placeholder" }, extension).files);
      return { id: `overlay-${index + 1}`, recipe: sceneId, startMs: overlay.startMs, durationMs: overlay.durationMs };
    });
    for (const cue of blueprint.cues) markers.push({ atMs: cue.atMs, label: cue.label, kind: "cue" });
    const captions = blueprint.captions.length ? `${request.id}.captions.srt` : undefined;
    if (captions) files.push({ path: captions, text: formatSrt(blueprint.captions) });
    const frame = ASPECT_FRAMES[aspect.data];
    const composition = { $schema: COMPOSITION_SCHEMA_POINTER, version: 1, id: request.id, title: request.title ?? blueprint.title, width: frame.width, height: frame.height, fps: 30, seed: 1, scenes, assets: [],
      ...(overlays.length ? { overlays } : {}), ...(markers.length ? { markers: markers.sort((a, b) => a.atMs - b.atMs) } : {}),
      ...(captions ? { captions: { file: captions, style: "karaoke" } } : {}) };
    files.push({ path: `${request.id}.composition.json`, text: JSON.stringify(composition, null, 2) + "\n" });
    files.push({ path: `${request.id}.brief.md`, text: blueprintBrief(blueprint, request.id, composition.scenes, cursor) });
    await withBrandFile(root, [...blueprint.scenes, ...blueprint.overlays].map(scene => findTemplate(scene.template)!), files);
    await writePlanned(root, files);
    const catalog = await discoverRecipes(root);
    const sceneIssues = catalog.issues.filter(issue => scenes.some(scene => issue.path.startsWith(`${SCENE_RECIPE_DIRECTORY}/${scene.recipe}.`)));
    if (sceneIssues.length) return { success: false, command, issues: sceneIssues.map(issue => normalizeIssue({ code: "ERR_SCENE_INVALID", ...issue })), next: ["velora validate --json"] };
    return { success: true, command, data: { files: files.map(file => file.path), composition: `${request.id}.composition.json`, blueprint: blueprint.id, aspect: aspect.data, durationMs: cursor, brief: blueprint.brief, slot: slot.kind },
      ...(warnings.length ? { warnings } : {}),
      next: [...(project.adapter ? ["velora sync --json"] : []), `velora validate --composition ${request.id}.composition.json --json`, `velora render --composition ${request.id}.composition.json --out ${request.id}.mp4 --json`] };
  } catch (error) {
    const known = error instanceof Error && "code" in error;
    const nested = known && "issues" in error && Array.isArray(error.issues) ? (error.issues as CliIssue[]) : undefined;
    const issues = (nested ?? [{ code: known ? String(error.code) : "ERR_INTERNAL", message: error instanceof Error ? error.message : "Template command failed.", ...(known && "target" in error && typeof error.target === "string" ? { path: error.target } : {}) }]).map(normalizeIssue);
    return { success: false, command, issues, next: nextForIssues(issues) };
  }
}

export type BrandCommandResult =
  | { success: true; command: "brand"; data: unknown; warnings?: CliIssue[]; next?: string[] }
  | { success: false; command: "brand"; issues: CliIssue[]; next: string[] };
const BRAND_SCHEMA_POINTER = "./node_modules/@adityadeokar/velora/schemas/brand.schema.json";
/** velora brand init|check: scaffold velora.brand.json (optionally seeded from CSS custom properties) or validate it. */
export async function executeBrandCommand(operation: "brand-init" | "brand-check", input: Record<string, unknown>, context: { root: string }): Promise<BrandCommandResult> {
  try {
    const root = await services.canonicalRoot(context.root);
    const existing = await services.readText(root, BRAND_FILE, 256_000);
    if (operation === "brand-check") {
      if (existing === undefined) throw Object.assign(new Error(`No ${BRAND_FILE} in this project. Run velora brand init.`), { code: "ERR_BRAND_INVALID", target: BRAND_FILE });
      let document: unknown;
      try { document = parseJsonDocument(existing); }
      catch { throw Object.assign(new Error(`${BRAND_FILE} is not valid JSON.`), { code: "ERR_BRAND_INVALID", target: BRAND_FILE }); }
      const parsed = BrandSchema.safeParse(document);
      if (!parsed.success) {
        const issues = parsed.error.issues.map(issue => normalizeIssue({ code: "ERR_BRAND_INVALID", path: `${BRAND_FILE}#${issue.path.join(".")}`, message: issue.message }));
        return { success: false, command: "brand", issues, next: nextForIssues(issues) };
      }
      const warnings: CliIssue[] = [];
      for (const token of ["text", "muted"] as const) {
        const ratio = contrastRatio(parsed.data.colors[token], parsed.data.colors.background);
        if (ratio !== undefined && ratio < 4.5)
          warnings.push(normalizeIssue({ code: "WARN_BRAND_CONTRAST", path: `${BRAND_FILE}#colors.${token}`, message: `colors.${token} has ${ratio.toFixed(2)}:1 contrast on the background; titles and captions need 4.5:1.` }));
      }
      if (parsed.data.logo && !(await services.isRegularFile(root, parsed.data.logo)) && !(await services.isRegularFile(root, `${ASSETS_DIRECTORY}/${parsed.data.logo}`)))
        warnings.push(normalizeIssue({ code: "WARN_BRAND_LOGO", path: `${BRAND_FILE}#logo`, message: `Logo ${parsed.data.logo} is not a project file; templates show the brand name instead.` }));
      return { success: true, command: "brand", data: { file: BRAND_FILE, brand: parsed.data }, ...(warnings.length ? { warnings } : {}) };
    }
    if (existing !== undefined) throw Object.assign(new Error(`${BRAND_FILE} already exists. Edit it, or run velora brand check.`), { code: "output-exists", target: BRAND_FILE });
    const name = typeof input.name === "string" && input.name.trim() ? input.name.trim() : await packageTitle(root);
    let seeded: ReturnType<typeof brandTokensFromCss> | undefined;
    if (typeof input.fromCss === "string") {
      const target = services.relativeTarget(input.fromCss.replace(/^\.\//, ""));
      if (!/\.(css|scss|less|pcss)$/i.test(target)) throw Object.assign(new Error("--from-css takes a stylesheet (.css, .scss, .less)."), { code: "invalid-input", target: "fromCss" });
      const css = await services.readText(root, target, 2_000_000);
      if (css === undefined) throw Object.assign(new Error(`Stylesheet ${target} was not found.`), { code: "invalid-input", target: "fromCss" });
      seeded = brandTokensFromCss(css);
    }
    const brand = BrandSchema.parse({ version: 1, name, ...(seeded ? { colors: completeBrandColors(seeded.colors), fonts: seeded.fonts, ...(seeded.radius !== undefined ? { radius: seeded.radius } : {}) } : {}) });
    const text = JSON.stringify({ $schema: BRAND_SCHEMA_POINTER, ...brand }, null, 2) + "\n";
    await services.atomicWrite(root, BRAND_FILE, text, undefined);
    return { success: true, command: "brand", data: { file: BRAND_FILE, brand, ...(seeded ? { fromCss: { colors: Object.keys(seeded.colors), fonts: Object.keys(seeded.fonts), customProperties: seeded.found.length } } : {}) },
      next: ["velora brand check --json"] };
  } catch (error) {
    const known = error instanceof Error && "code" in error;
    const issues = [normalizeIssue({ code: known ? String((error as { code: unknown }).code) : "ERR_INTERNAL", message: error instanceof Error ? error.message : "Brand command failed.", ...(known && typeof (error as { target?: unknown }).target === "string" ? { path: (error as unknown as { target: string }).target } : {}) })];
    return { success: false, command: "brand", issues, next: nextForIssues(issues) };
  }
}
async function packageTitle(root: string): Promise<string> {
  try {
    const name = (parseJsonDocument((await services.readText(root, "package.json", 256_000)) ?? "{}") as { name?: unknown }).name;
    return typeof name === "string" && name ? name.replace(/^@[^/]+\//, "").split(/[-_]/).map(part => part ? part[0].toUpperCase() + part.slice(1) : part).join(" ") : "Your product";
  } catch { return "Your product"; }
}

export type EditorialCommandResult =
  | { success: true; command: "audio" | "compose" | "review"; data: unknown; warnings?: CliIssue[]; next?: string[] }
  | { success: false; command: "audio" | "compose" | "review"; issues: CliIssue[]; next: string[] };
const editorialFault = (code: string, message: string, target?: string): never => { throw Object.assign(new Error(message), { code, ...(target ? { target } : {}) }); };
/**
 * Editorial operations: `audio beats` (beat report, optional --write-markers), `compose snap` (a dry-run
 * diff of cut moves onto beat markers; --write applies it) and `review` (advisory editorial review).
 * Compositions are only ever rewritten with an explicit write flag.
 */
export async function executeEditorialCommand(operation: "audio-beats" | "compose-snap" | "review", input: Record<string, unknown>, context: { root: string }): Promise<EditorialCommandResult> {
  const command = operation === "audio-beats" ? "audio" as const : operation === "compose-snap" ? "compose" as const : "review" as const;
  try {
    const root = await services.canonicalRoot(context.root);
    const compositionFile = typeof input.composition === "string" ? input.composition : undefined;
    const load = async () => {
      if (!compositionFile) return editorialFault("ERR_MISSING_VALUE", `${command} needs --composition.`, "composition");
      const loaded = await loadCompositionTracks(root, compositionFile);
      if ("issues" in loaded) throw Object.assign(new Error(loaded.issues[0].message), { code: loaded.issues[0].code, target: loaded.issues[0].path, issues: loaded.issues.map(normalizeIssue) });
      return loaded;
    };
    if (operation === "review") {
      const { composition } = await load();
      const catalog = await discoverRecipes(root);
      const result = reviewComposition(composition, catalog.scenes, { ...(typeof input.platform === "string" ? { platform: input.platform } : {}) });
      return { success: true, command, data: { composition: compositionFile, ...result, advisoryCount: result.advisories.length } };
    }
    if (operation === "audio-beats") {
      let file = typeof input.file === "string" ? input.file : undefined;
      let loaded: Awaited<ReturnType<typeof load>> | undefined;
      if (!file) {
        loaded = await load();
        const track = loaded.composition.audio.find(entry => entry.kind === "music") ?? loaded.composition.audio[0];
        if (!track) return editorialFault("ERR_AUDIO_INVALID", "The composition has no audio track; pass --file <music file>.", "file");
        file = resolveAssetId(loaded.assets, loaded.aliases, track.assetId);
        if (!file) return editorialFault("ERR_ASSET_NOT_FOUND", `Audio asset "${track.assetId}" was not discovered.`, "file");
      }
      const target = services.relativeTarget(file.replace(/^\.\//, ""));
      const absolute = await services.scopedPath(root, target);
      if (!(await services.isRegularFile(root, target))) return editorialFault("ERR_ASSET_NOT_FOUND", `Audio file ${target} was not found.`, "file");
      const report = analyzeRhythm(await services.decodePcm(absolute, RHYTHM_SAMPLE_RATE), RHYTHM_SAMPLE_RATE);
      const warnings: CliIssue[] = report.confidence < 0.2 ? [normalizeIssue({ code: "WARN_BEATS_UNCERTAIN", path: target, message: `Beat confidence is ${report.confidence.toFixed(2)}; the music may lack a steady pulse. Check the beat grid by ear before snapping.` })] : [];
      let markers: number | undefined;
      if (input.writeMarkers) {
        loaded ??= await load();
        const text = await services.readText(root, compositionFile!, 256_000);
        if (text === undefined) return editorialFault("source-changed", "Composition source disappeared.", "composition");
        const document = parseJsonDocument(text) as Record<string, unknown>;
        const keep = (Array.isArray(document.markers) ? document.markers as { kind?: string }[] : []).filter(marker => marker.kind !== "beat" && marker.kind !== "downbeat");
        const downbeats = new Set(report.downbeats);
        const written = [...keep, ...report.beats.map(atMs => ({ atMs, label: "", kind: downbeats.has(atMs) ? "downbeat" : "beat" }))].sort((a, b) => ((a as { atMs: number }).atMs) - ((b as { atMs: number }).atMs));
        await services.atomicWrite(root, compositionFile!, JSON.stringify({ ...document, markers: written }, null, 2) + "\n", text);
        markers = report.beats.length;
      }
      return { success: true, command, data: { file: target, bpm: report.bpm, confidence: Math.round(report.confidence * 1000) / 1000, beats: report.beats, downbeats: report.downbeats, onsets: report.onsets.length, durationMs: Math.round(report.durationMs), ...(markers !== undefined ? { markersWritten: markers } : {}) },
        ...(warnings.length ? { warnings } : {}), next: compositionFile ? [`velora compose snap --composition ${compositionFile} --to beats --json`] : [] };
    }
    const { composition } = await load();
    const to = input.to === "downbeats" ? "downbeat" : "beat";
    const grid = composition.markers.filter(marker => to === "beat" ? marker.kind === "beat" || marker.kind === "downbeat" : marker.kind === "downbeat").map(marker => marker.atMs);
    if (!grid.length) return editorialFault("ERR_MARKERS_MISSING", `The composition has no ${to} markers. Run velora audio beats --composition ${compositionFile} --write-markers first.`, "markers");
    const tolerance = typeof input.tolerance === "number" ? input.tolerance : 120;
    const plan = snapToBeats(composition.scenes.map(scene => ({ id: scene.id, startMs: scene.startMs, durationMs: scene.durationMs,
      overlapMs: scene.transition && isOverlapTransition(scene.transition.type) ? scene.transition.durationMs : 0 })), grid, tolerance);
    let written = false;
    if (input.write && plan.changes.length) {
      const text = await services.readText(root, compositionFile!, 256_000);
      if (text === undefined) return editorialFault("source-changed", "Composition source disappeared.", "composition");
      const document = parseJsonDocument(text) as { scenes: Record<string, unknown>[] };
      for (const change of plan.changes) {
        const scene = document.scenes.find(entry => entry.id === change.id);
        if (scene) scene[change.field] = change.to;
      }
      await services.atomicWrite(root, compositionFile!, JSON.stringify(document, null, 2) + "\n", text);
      written = true;
    }
    return { success: true, command, data: { composition: compositionFile, to: `${to}s`, toleranceMs: tolerance, changes: plan.changes, unsnapped: plan.unsnapped, written },
      next: written ? [`velora validate --composition ${compositionFile} --json`] : plan.changes.length ? [`velora compose snap --composition ${compositionFile} --to ${to}s --write --json`] : [] };
  } catch (error) {
    const known = error instanceof Error && "code" in error;
    const nested = known && "issues" in error && Array.isArray(error.issues) ? (error.issues as CliIssue[]) : undefined;
    const issues = (nested ?? [{ code: known ? String((error as { code: unknown }).code) : "ERR_INTERNAL", message: error instanceof Error ? error.message : `${command} failed.`, ...(known && typeof (error as { target?: unknown }).target === "string" ? { path: (error as unknown as { target: string }).target } : {}) }]).map(normalizeIssue);
    return { success: false, command, issues, next: nextForIssues(issues) };
  }
}
