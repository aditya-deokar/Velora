async function portableFiles(root:string, project:ProjectState, catalog:string) {
  const allowed=project.adapter==="next-app" ? ["app/velora/page.jsx","src/app/velora/page.jsx"]
    : project.adapter==="next-pages" ? ["pages/velora.jsx","src/pages/velora.jsx"] : ["src/velora/ProjectPreview.jsx"];
  if(!allowed.includes(project.entry))throw fault("conflict","Recorded entry is not a valid host connection.");
  const files = portableIntegration(project,catalog);
  // Alternative source extensions must not shadow our generated route/component.
  for (const target of Object.keys(files)) {
    await services.scopedPath(root,target);
    if (/\.jsx$/.test(target)) for (const extension of ["js","tsx","ts","mjs"]) {
      const other=target.replace(/\.jsx$/,"."+extension);
      if (await services.isRegularFile(root,other)) throw fault("conflict","An existing file owns this route or component; use --adapter react to choose a manual connection instead.",other);
    }
  }
  if(project.adapter === "next-app") for(const extension of ["ts","js"]) {
    const other=project.entry.replace(/page.jsx$/,"route."+extension);
    if(await services.isRegularFile(root,other))throw fault("conflict","An existing route handler owns /velora. Use --adapter react.",other);
  }
  return files;
}
async function initializePortable(root:string, host:PortableHost, packageSource?:string):Promise<ProjectResult> {
  const saved=await stateFor(root);
  const pendingText=await services.readText(root,portablePendingPath);
  const pending=pendingText===undefined?undefined:decode(pendingText,ManagedSchema,portablePendingPath);
  const existingText=await services.readText(root,managedPath);
  const existing=existingText===undefined?undefined:decode(existingText,ManagedSchema,managedPath);
  const project=saved.project??pending?.project??ProjectStateSchema.parse({version:1,projectId:services.newProjectId(),entry:host.entry,packageManager:"npm",adapter:host.adapter});
  if(project.adapter!==host.adapter||project.entry!==host.entry)throw fault("conflict","Existing Velora setup uses another host connection.");
  for(const record of [pending,existing])if(record && JSON.stringify(record.project)!==JSON.stringify(project))throw fault("conflict","Velora setup identity changed; inspect .velora before retrying.");
  const catalog=existing?.files["src/velora/catalog.js"]??pending?.files["src/velora/catalog.js"]??await catalogSource(root);
  const files=await portableFiles(root,project,catalog);
  const generated=agentHandoff();
  files[generated.handoff.path]=generated.text;
  if(pending && JSON.stringify(pending.files)!==JSON.stringify(files))throw fault("conflict","Pending setup differs from the generated connection; review it before retrying.");
  if(existing && JSON.stringify(existing.files)!==JSON.stringify(files))throw fault("conflict","Managed Velora files differ from this installed adapter.");
  // Finish all conflict/dependency checks before any writes.
  for(const [target,text] of Object.entries(files)) {
    const current=await services.readText(root,target);
    if(current!==undefined && current!==text)throw fault("conflict","Velora will not overwrite an existing or edited file. Preserve it before retrying.",target);
  }
  await hostDependenciesValid(root);
  const installed=await installationValid(root,false);
  const source=installed?undefined:await sourceForInstall(root,packageSource);
  if(existing && saved.project && !pending) {
    await verifyPortable(root,project);
    return {success:true,data:{project,changed:false,handoff:generated.handoff,integration:integrationInfo(project)}};
  }
  const journal=JSON.stringify({project,files},null,2)+"\n";
  if(!pendingText)await services.atomicWrite(root,portablePendingPath,journal,undefined);
  if(source){await services.installPackage(root,source);await installationValid(root);}
  for(const [target,text] of Object.entries(files)) {
    const current=await services.readText(root,target);
    if(current===undefined)await services.atomicWrite(root,target,text,undefined);
    else if(current!==text)throw fault("conflict","File changed during setup.",target);
  }
  if(!existing)await services.atomicWrite(root,managedPath,journal,undefined);
  if(!saved.project)await services.atomicWrite(root,statePath,JSON.stringify(project,null,2)+"\n",saved.text);
  await services.removeText(root,portablePendingPath,pendingText??journal);
  return {success:true,data:{project,changed:true,handoff:generated.handoff,integration:integrationInfo(project)}};
}
async function verifyPortable(root:string,project:ProjectState) {
  if(await services.readText(root,portablePendingPath)!==undefined)throw fault("incomplete-setup","Run velora init to resume interrupted setup.");
  const text=await services.readText(root,managedPath);
  if(text===undefined)throw fault("incomplete-setup","Missing managed connection. Run velora init.");
  const managed=decode(text,ManagedSchema,managedPath);
  if(JSON.stringify(managed.project)!==JSON.stringify(project))throw fault("conflict","Managed project identity differs.");
  const expected=await portableFiles(root,project,managed.files["src/velora/catalog.js"]??"");
  expected["VELORA.md"]=agentHandoff().text;
  if(JSON.stringify(expected)!==JSON.stringify(managed.files))throw fault("conflict","Managed file list differs from the canonical connection.");
  for(const [target,content] of Object.entries(expected))if(await services.readText(root,target)!==content)throw fault("conflict","Generated connection changed or is missing. Keep customizations in your scene components.",target);
  await installationValid(root);
}
async function synchronize(root:string):Promise<ProjectResult> {
  const project=(await stateFor(root)).project;
  if(!project)throw fault("not-initialized","Run velora init first.");
  if(!project.adapter){await load(root);return {success:true,data:{project,changed:false}};}
  const transactionPath=".velora/catalog-pending.json";
  const interrupted=await services.readText(root,transactionPath);
  if(interrupted!==undefined) {
    const pending=decode(interrupted,z.strictObject({before:z.string(),after:z.string()}),transactionPath);
    const recordText=await services.readText(root,managedPath);
    if(recordText===undefined)throw fault("conflict","Missing catalog ownership record.");
    const record=decode(recordText,ManagedSchema,managedPath);
    const current=await services.readText(root,"src/velora/catalog.js");
    if(![pending.before,pending.after].includes(record.files["src/velora/catalog.js"]) || ![pending.before,pending.after].includes(current??""))
      throw fault("conflict","Catalog changed during interrupted sync.");
    if(current!==pending.after)await services.atomicWrite(root,"src/velora/catalog.js",pending.after,current);
    if(record.files["src/velora/catalog.js"]!==pending.after) {
      record.files["src/velora/catalog.js"]=pending.after;
      await services.atomicWrite(root,managedPath,JSON.stringify(record,null,2)+"\n",recordText);
    }
    await services.removeText(root,transactionPath,interrupted);
  }
  await verifyPortable(root,project);
  const target="src/velora/catalog.js";
  const text=await catalogSource(root);
  const savedText=(await services.readText(root,managedPath))!;
  const managed=decode(savedText,ManagedSchema,managedPath);
  const original=managed.files[target];
  if(text===original)return {success:true,data:{project,changed:false}};
  // Journal registry replacement so a crash between registry/ownership writes is recoverable.
  const transaction=JSON.stringify({before:original,after:text});
  const pending=await services.readText(root,transactionPath);
  if(pending!==undefined&&pending!==transaction)throw fault("conflict","A catalog sync is pending. Restore the previous file set before retrying.");
  if(pending===undefined)await services.atomicWrite(root,transactionPath,transaction,undefined);
  await services.atomicWrite(root,target,text,original);
  managed.files[target]=text;
  await services.atomicWrite(root,managedPath,JSON.stringify(managed,null,2)+"\n",savedText);
  await services.removeText(root,transactionPath,transaction);
  return {success:true,data:{project,changed:true}};
}

// SOURCE OF TRUTH: executeDoctorCommand project-side health checks.
// WHAT: read-only environment and project diagnostics with stable codes.
// WHY: agents diagnose init/render failures before mutating anything.
// WHERE: cli/index merges these checks with capture-prerequisite probes;
// services owns all filesystem/process effects.
const DoctorInputSchema = z.strictObject({ url: OpenPreviewSchema.shape.url.optional() });
function doctorCheck(checks: DoctorCheck[], issues: CliIssue[], id: string, label: string, pass: boolean, detail?: string, code?: string, hint?: string) {
  checks.push({ id, label, pass, ...(detail ? { detail } : {}), ...(hint ? { hint } : {}), ...(code && !pass ? { code } : {}) });
  if (!pass) issues.push(normalizeIssue({ code: code ?? "ERR_INTERNAL", message: detail ? `${label}: ${detail}` : label, path: `doctor.${id}`, ...(hint ? { hint } : {}) }));
}
function faultCode(error: unknown): string | undefined {
  return error instanceof Error && "code" in error && typeof error.code === "string" ? error.code : undefined;
}
export async function executeDoctorCommand(input: unknown, context: { root: string }): Promise<DoctorResult> {
  const checks: DoctorCheck[] = [];
  const issues: CliIssue[] = [];
  const parsed = DoctorInputSchema.safeParse(input);
  if (!parsed.success) {
    for (const issue of parsed.error.issues)
      issues.push(normalizeIssue({ code: "invalid-input", message: issue.message, path: `doctor.${issue.path.join(".") || "url"}` }));
    return { success: false as const, command: "doctor" as const, data: { checks }, issues, next: nextForIssues(issues) };
  }
  if (!context || typeof context.root !== "string") {
    doctorCheck(checks, issues, "scope", "Project root", false, "Provide an absolute local project directory.", "invalid-scope");
    return { success: false as const, command: "doctor" as const, data: { checks }, issues, next: nextForIssues(issues) };
  }
  let root: string;
  try {
    root = await services.canonicalRoot(context.root);
    doctorCheck(checks, issues, "scope", "Project root", true, root);
  } catch (error) {
    doctorCheck(checks, issues, "scope", "Project root", false,
      error instanceof Error ? error.message : "Unreadable project root.", faultCode(error) ?? "invalid-scope");
    return { success: false as const, command: "doctor" as const, data: { checks }, issues, next: nextForIssues(issues) };
  }
  const nodeVersion = services.runtimeVersion();
  const nodeMatch = /^v?(\d+)\.(\d+)/.exec(nodeVersion);
  const nodeOk = !!nodeMatch && (Number(nodeMatch[1]) > 22 || (Number(nodeMatch[1]) === 22 && Number(nodeMatch[2]) >= 12));
  doctorCheck(checks, issues, "node", "Node runtime", nodeOk,
    nodeOk ? `${nodeVersion} satisfies >=22.12.0.` : `${nodeVersion} is below the required >=22.12.0.`,
    "ERR_NODE_UNSUPPORTED");
  try {
    const pkg = await packageAt(root, "package.json");
    if (!pkg) doctorCheck(checks, issues, "package", "npm package", false, "No package.json at the project root.", "unsupported-project");
    else if (pkg.workspaces !== undefined || (pkg.packageManager && !/^npm@\d/.test(pkg.packageManager)))
      doctorCheck(checks, issues, "package", "npm package", false, "Automatic setup supports a single-root npm project.", "unsupported-project");
    else doctorCheck(checks, issues, "package", "npm package", true, pkg.name ?? "package.json is a single-root npm package.");
  } catch (error) {
    doctorCheck(checks, issues, "package", "npm package", false,
      error instanceof Error ? error.message : "Unreadable package.json.", faultCode(error) ?? "invalid-file");
  }
  try {
    await hostDependenciesValid(root);
    doctorCheck(checks, issues, "react", "React renderer", true, "Installed React and React DOM satisfy 18.2+ or 19.x.");
  } catch (error) {
    doctorCheck(checks, issues, "react", "React renderer", false,
      error instanceof Error ? error.message : "Missing or incompatible React installation.", "ERR_REACT_UNSUPPORTED");
  }
  try {
    const installed = await installationValid(root, false);
    if (installed) doctorCheck(checks, issues, "toolkit", "Velora toolkit", true, "Installed velora package exposes the preview entry.");
    else doctorCheck(checks, issues, "toolkit", "Velora toolkit", false, "Velora is not installed in this project.", "ERR_TOOLKIT_MISSING");
  } catch (error) {
    doctorCheck(checks, issues, "toolkit", "Velora toolkit", false,
      error instanceof Error ? error.message : "Velora installation conflict.", faultCode(error) ?? "ERR_TOOLKIT_MISSING");
  }
  try {
    const catalog = await discoverRecipes(root);
    if (catalog.issues.length) doctorCheck(checks, issues, "scenes", "Scene catalog", false,
      catalog.issues.map((issue) => `${issue.path}: ${issue.message}`).join("\n").slice(0, 500), "ERR_SCENE_INVALID");
    else doctorCheck(checks, issues, "scenes", "Scene catalog", true,
      catalog.scenes.length ? `${catalog.scenes.length} scene${catalog.scenes.length === 1 ? "" : "s"} validated.` : "No scenes yet; the catalog is valid and empty.");
  } catch (error) {
    doctorCheck(checks, issues, "scenes", "Scene catalog", false,
      error instanceof Error ? error.message : "Unable to read the scene catalog.", faultCode(error) ?? "ERR_SCENE_INVALID");
  }
  if (parsed.data.url !== undefined) {
    try {
      await services.fetchText(parsed.data.url);
      doctorCheck(checks, issues, "dev-server", "Dev server", true, `${parsed.data.url} responds.`);
    } catch {
      doctorCheck(checks, issues, "dev-server", "Dev server", false,
        `No supported dev server at ${parsed.data.url}. Run npm run dev first.`, "ERR_SERVER_UNREACHABLE");
    }
  }
  if (!issues.length) return { success: true as const, command: "doctor" as const, data: { checks } };
  return { success: false as const, command: "doctor" as const, data: { checks }, issues, next: nextForIssues(issues) };
}

