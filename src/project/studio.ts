/** SOURCE OF TRUTH: STUDIO_BASE, STUDIO_PROXY_PATTERN, isLoopbackUrl, studioWorkspaceFiles, studioRunConfig.
 * WHAT: any-site mode's pure plan: the managed studio workspace (pinned React, Vite and the React plugin; the
 * Velora package is aliased to the running CLI), its Vite config (studio under /__velora/, every other path
 * proxied to the target site, frame-blocking headers stripped in development), the studio entry that loads the
 * project's scenes, compositions and assets, and the per-run config file.
 * WHY: Astro, SvelteKit, Rails, Django or static sites get templates, quick shots, compositions and delivery
 * of their real pages through a same-origin proxy without React or Vite ever entering their project.
 * WHERE: project/commands executeStudioCommand provisions and starts it through services; capture and the CLI
 * reach the studio at <origin>/__velora/ (previewBase).
 */
export const STUDIO_BASE = "/__velora/";
export const STUDIO_DEFAULT_PORT = 5180;
// Everything except the studio's own base and Vite internals goes to the target site.
export const STUDIO_PROXY_PATTERN = "^/(?!__velora(?:/|$)|@vite/|@fs/|@id/|@react-refresh|node_modules/\\.vite/).*";
export const STUDIO_PINNED = Object.freeze({
  react: "19.2.0", "react-dom": "19.2.0", vite: "7.3.6", "@vitejs/plugin-react": "5.1.0",
});
// scheme://host[:port][/path] with a loopback host and no credentials; parsed without host URL globals.
const LOOPBACK_URL = /^(https?):\/\/(127\.0\.0\.1|localhost|\[::1\])(:\d{1,5})?(?:[/?#][^\s@]*)?$/i;
/** Only http(s) loopback origins: the proxy never reaches the network. */
export function isLoopbackUrl(value: string): boolean {
  const match = LOOPBACK_URL.exec(value.trim());
  return !!match && (match[3] === undefined || Number(match[3].slice(1)) <= 65535);
}
/** scheme://host[:port] of a loopback URL (lowercased scheme and host). */
export function loopbackOrigin(value: string): string {
  const match = LOOPBACK_URL.exec(value.trim());
  if (!match) throw new Error(`${value} is not a loopback URL.`);
  return `${match[1].toLowerCase()}://${match[2].toLowerCase()}${match[3] ?? ""}`;
}
export type StudioRunConfig = { projectRoot: string; projectId: string; site: string; port: number; packageRoot: string };
export function studioRunConfig(input: StudioRunConfig): string {
  const posix = (value: string) => value.replace(/\\/g, "/");
  return JSON.stringify({ ...input, projectRoot: posix(input.projectRoot), packageRoot: posix(input.packageRoot), site: loopbackOrigin(input.site) }, null, 2) + "\n";
}

